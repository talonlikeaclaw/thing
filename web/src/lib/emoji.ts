/**
 * A small, curated emoji catalogue for the icon picker.
 *
 * It is deliberately not the whole Unicode set: a searchable shortlist covers
 * what a space, type or record is usually named after, and the picker still
 * accepts any other emoji typed into its custom field. No network request and
 * no dependency.
 */

export interface EmojiEntry {
  char: string;
  name: string;
  keywords: string;
}

export interface EmojiGroup {
  name: string;
  entries: EmojiEntry[];
}

type Row = readonly [char: string, name: string, keywords?: string];

function group(name: string, rows: readonly Row[]): EmojiGroup {
  return {
    name,
    entries: rows.map(([char, entryName, keywords = ""]) => ({
      char,
      name: entryName,
      keywords,
    })),
  };
}

