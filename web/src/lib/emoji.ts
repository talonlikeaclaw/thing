/** Matches every term (case-insensitively) against the name and keywords. */
export function searchEmoji(query: string, limit = 48): EmojiEntry[] {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (terms.length === 0) {
    return [];
  }
  const found: EmojiEntry[] = [];
  const seen = new Set<string>();
  for (const entry of EMOJI_GROUPS.flatMap((group) => group.entries)) {
    const haystack = `${entry.char} ${entry.name} ${entry.keywords}`.toLowerCase();
    if (!seen.has(entry.char) && terms.every((term) => haystack.includes(term))) {
      seen.add(entry.char);
      found.push(entry);
      if (found.length === limit) {
        break;
      }
    }
  }
  return found;
}
